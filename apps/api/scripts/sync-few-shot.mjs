#!/usr/bin/env node
/**
 * Sync few-shot seeds from speech-ml into apps/api as a checked-in snapshot.
 *
 * DEV-14: the API must stay hermetic at deploy time — no runtime dependency on
 * speech-ml. This script copies the exported JSONL buckets from speech-ml's
 * eval/few_shot/ into apps/api/src/llm/few-shot/data/ (kept for review diffs and
 * provenance), and generates a TypeScript module (few-shot-data.ts) that the API
 * imports directly. Generating a .ts module — rather than reading .jsonl at
 * runtime — means tsc bundles the data normally into dist/, so production builds
 * carry the seeds with no file IO and no copy step.
 *
 * Usage:
 *   node scripts/sync-few-shot.mjs                 # default source path
 *   FEW_SHOT_SRC=/path/to/eval/few_shot node scripts/sync-few-shot.mjs
 *
 * Parity: the record shape mirrors speech-ml/eval/few_shot/*.jsonl and the
 * rendering in src/llm/few-shot.ts stays consistent with the eval harness'
 * prompt builders (speech-ml/eval/runner/prompts.py). If the export schema
 * changes upstream, re-run this script and review the diff.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const API_ROOT = join(HERE, "..");
const SRC =
  process.env.FEW_SHOT_SRC ?? "/home/user/speech-ml/eval/few_shot";
const OUT_DIR = join(API_ROOT, "src", "llm", "few-shot");
const DATA_DIR = join(OUT_DIR, "data");

if (!existsSync(SRC)) {
  console.error(`few-shot source not found: ${SRC}`);
  process.exit(1);
}

function sourceProvenance() {
  // Best-effort: capture the speech-ml commit/date for the provenance note.
  const repoRoot = join(SRC, "..", "..");
  try {
    const commit = execFileSync("git", ["-C", repoRoot, "rev-parse", "HEAD"], {
      encoding: "utf8",
    }).trim();
    const date = execFileSync(
      "git",
      ["-C", repoRoot, "log", "-1", "--format=%cI"],
      { encoding: "utf8" },
    ).trim();
    return { commit, date };
  } catch {
    return { commit: "unknown", date: "unknown" };
  }
}

// 1. Copy the raw JSONL snapshot (review diffs + provenance).
rmSync(DATA_DIR, { recursive: true, force: true });
mkdirSync(DATA_DIR, { recursive: true });

const jsonlFiles = readdirSync(SRC)
  .filter((f) => f.endsWith(".jsonl"))
  .sort();
for (const f of jsonlFiles) {
  copyFileSync(join(SRC, f), join(DATA_DIR, f));
}
if (existsSync(join(SRC, "index.json"))) {
  copyFileSync(join(SRC, "index.json"), join(DATA_DIR, "index.json"));
}

// 2. Parse every bucket into in-memory records.
/** @typedef {Record<string, unknown>} FewShotRecord */
/** @type {Record<string, FewShotRecord[]>} */
const buckets = {};
for (const f of jsonlFiles) {
  const specialty = f.replace(/\.jsonl$/, "");
  const lines = readFileSync(join(DATA_DIR, f), "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  buckets[specialty] = lines.map((l) => JSON.parse(l));
}

const provenance = sourceProvenance();
const syncedAt = new Date().toISOString();

// 3. Emit the generated TS module the API imports.
const orderedSpecialties = Object.keys(buckets).sort();
const total = orderedSpecialties.reduce(
  (n, s) => n + buckets[s].length,
  0,
);

const header = `// AUTO-GENERATED by scripts/sync-few-shot.mjs — DO NOT EDIT BY HAND.
//
// Few-shot persona seeds vendored from speech-ml (eval/few_shot).
// Re-run \`npm run sync:few-shot\` in apps/api to regenerate.
//
// Provenance:
//   source:        speech-ml/eval/few_shot
//   source commit: ${provenance.commit}
//   source date:   ${provenance.date}
//   synced at:     ${syncedAt}
//   total records: ${total}
`;

const recordType = `export type FewShotRecord = {
  persona_id: string;
  specialty: string;
  care_model?: string;
  jurisdiction?: string;
  presenting_concern?: string;
  history?: string;
  intake_answers?: Record<string, unknown>;
  expected_triage_outcome?: string;
  expected_session_plan_domain?: string;
  prep_brief_gist?: string;
  session_plan_gist?: string;
  summary_gist?: string;
};
`;

const bucketEntries = orderedSpecialties
  .map(
    (s) =>
      `  ${JSON.stringify(s)}: ${JSON.stringify(buckets[s])} as FewShotRecord[],`,
  )
  .join("\n");

const body = `
export const FEW_SHOT_PROVENANCE = {
  source: "speech-ml/eval/few_shot",
  sourceCommit: ${JSON.stringify(provenance.commit)},
  sourceDate: ${JSON.stringify(provenance.date)},
  syncedAt: ${JSON.stringify(syncedAt)},
  total: ${total},
} as const;

/** Few-shot examples grouped by specialty bucket (filename stem). */
export const FEW_SHOT_BUCKETS: Record<string, FewShotRecord[]> = {
${bucketEntries}
};
`;

writeFileSync(join(OUT_DIR, "few-shot-data.ts"), header + "\n" + recordType + body);

// 4. Provenance note (also human-readable, sits next to the data).
writeFileSync(
  join(OUT_DIR, "PROVENANCE.json"),
  JSON.stringify(
    {
      source: "speech-ml/eval/few_shot",
      sourceCommit: provenance.commit,
      sourceDate: provenance.date,
      syncedAt,
      total,
      buckets: Object.fromEntries(
        orderedSpecialties.map((s) => [s, buckets[s].length]),
      ),
    },
    null,
    2,
  ) + "\n",
);

console.log(
  `Synced ${total} few-shot records across ${orderedSpecialties.length} buckets from ${SRC}`,
);
